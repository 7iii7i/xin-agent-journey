# ===== 构建知识库（构建知识库.py）=====
# 作用：第一次运行时，把"电商文档 + 工厂文档"合并切片 → embedding 变向量 → 存盘到 data/。
# 之后 python main.py 启动时只会"加载"，不会重复下载模型/重新算。
# 🟢 懂框架：这台机器第一次跑会下载中文向量模型(约90MB)，之后就缓存了。
import os
import sqlite3

from rag import 知识库实例, 原始文档

# 工厂库存库（兄弟项目 factory_inventory 的 SQLite）。读它自动生成"物品说明段"。
工厂库路径 = os.path.join(os.path.dirname(__file__), "..", "factory_inventory", "factory.db")


def 读工厂文档():
    """从工厂库存 SQLite 读出 SKU 自动生成说明段 + 几条规则类文档。
    🟢 懂框架：结构化数据(SQLite) 也能"拼成非结构化文本"喂给 RAG 做语义检索——
    这正是"RAG 不替代 SQLite、但能用同一套检索回答"的实战写法。"""
    if not os.path.exists(工厂库路径):
        print("⚠️ 没找到工厂库存库，跳过工厂文档")
        return []
    conn = sqlite3.connect(工厂库路径)
    rows = conn.execute(
        "SELECT 编号,名称,类别,规格,数量,单位,安全库存,库位 FROM inventory"
    ).fetchall()
    conn.close()
    段 = []
    for 编号, 名称, 类别, 规格, 数量, 单位, 安全库存, 库位 in rows:
        段.append(
            f"{名称}（编号{编号}，类别{类别}）：规格{规格}，"
            f"当前库存{数量}{单位}，安全库存{安全库存}{单位}，库位{库位}。"
        )
    # 规则类文档（非结构化政策/流程，适合语义检索，不适合 SQL 精确查）
    段 += [
        "库存预警：当物品当前数量低于安全库存阈值时，需触发补货提醒，避免断料影响生产。",
        "入库流程：物料到货后核对编号与数量，登记入库增加库存并更新时间。",
        "出库流程：生产领料或发货时登记出库减少库存并更新时间，确保账实一致。",
        "品类划分：库存分成品（如法兰、外壳）、原料（如钢板、螺丝、铜线、塑料粒子）、"
        "备件（如电机、轴承、皮带、滤芯）三类，按类别管理与盘点。",
    ]
    return 段


if __name__ == "__main__":
    工厂文档 = 读工厂文档()
    全量文档 = 原始文档 + 工厂文档
    print(f"电商文档 {len(原始文档)} 段 + 工厂文档 {len(工厂文档)} 段 = 合并 {len(全量文档)} 段")

    知识库实例.构建(全量文档)

    print("\n=== 快速自测：电商问题 ===")
    for 问题 in ["耳机坏了能退吗", "今天下单什么时候发货"]:
        print(f"\n问题：{问题}")
        print(知识库实例.检索(问题, top_k=2))

    print("\n=== 快速自测：工厂问题 ===")
    for 问题 in ["螺丝库存多少", "原料有哪些品类", "什么情况下要补货"]:
        print(f"\n问题：{问题}")
        print(知识库实例.检索(问题, top_k=2))
