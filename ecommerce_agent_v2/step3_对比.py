# Step 3 对比演示：朴素关键词检索 vs 向量(语义)检索
# 同一份文档、同一批问题，看 RAG 的语义检索强在哪。
# 沙箱可跑：用「教学版概念 embedder」（无需下载大模型）。
# 真项目把 embedder 换成 bge 模型即可（见 rag.py 的 _取模型），原理相同、维度更高。
import numpy as np

原始文档 = [
    "退换货政策：商品签收后7天内，在不影响二次销售的前提下支持无理由退货，退货运费由买家承担。",
    "质保说明：电子类商品提供一年质保，非人为损坏可免费维修或换新。",
    "发货时效：现货商品当天16点前下单当日发出，预售商品以页面标注为准。",
    "蓝牙耳机X1：续航20小时，支持主动降噪，IPX4防水，售价299元。",
    "充电宝P2：容量20000mAh，支持22.5W快充，可同时充三台设备，售价129元。",
    "会员积分：每消费1元得1积分，100积分可抵1元，积分有效期12个月。",
    "优惠券使用：满199减30券不可与其他活动叠加，过期作废。",
    "客服时间：人工客服每日9:00-21:00在线，其余时段由智能客服解答。",
]

# 8 个主题维度（真实项目由 bge 模型自动学，这里手列教学用）
概念词 = {
    "退换": ["退", "换", "寄", "七", "天", "运", "退货", "无理由"],
    "质保": ["质保", "维修", "换新", "一年", "人为", "免费", "保"],
    "发货": ["发货", "当天", "预售", "时效", "下单", "页面", "发出"],
    "耳机": ["耳机", "降噪", "续航", "防水", "售价"],
    "充电宝": ["充电宝", "容量", "快充", "充三台"],
    "积分": ["积分", "会员", "消费", "抵"],
    "优惠": ["优惠券", "满", "减", "叠加", "活动", "过期", "便宜", "折扣"],
    "客服": ["客服", "人工", "在线", "时间", "每日", "半夜", "夜间", "几点", "下班", "上班", "找"],
}
维度名 = list(概念词.keys())


def 文档概念向量(d):
    return [1.0 if any(k in d for k in 概念词[c]) else 0.0 for c in 维度名]


def 问题概念向量(q):
    return [1.0 if any(k in q for k in 概念词[c]) else 0.0 for c in 维度名]


# ---- 朴素关键词检索：问题和文档逐字重叠（模拟 SQL LIKE 字面匹配）----
def 关键词检索(问题, top_k=1):
    问题字 = set(问题)
    得分 = [(len(问题字 & set(d)), i) for i, d in enumerate(原始文档)]
    得分.sort(key=lambda x: -x[0])
    return [原始文档[i] for _, i in 得分[:top_k]]


# ---- 向量(语义)检索：教学版概念点积 ----
文档矩阵 = np.array([文档概念向量(d) for d in 原始文档])


def 向量检索(问题, top_k=1):
    qv = np.array(问题概念向量(问题))
    sims = 文档矩阵 @ qv
    idx = np.argsort(-sims)[:top_k]
    return [原始文档[i] for i in idx]


# 测试问题 + 正确答案索引
用例 = [
    ("半夜能不能找你们", 7, "客服时间"),
    ("买多了有便宜吗", 6, "优惠券使用"),
    ("耳机质量差能退吗", 0, "退换货政策"),
    ("耳机续航多少", 3, "蓝牙耳机X1"),
    ("充电宝能充几个", 4, "充电宝P2"),
]

print("=" * 64)
print("Step 3 对比：朴素关键词检索  vs  向量(语义)检索")
print("=" * 64)
for 问题, 正确索引, 正确名 in 用例:
    词结果 = 关键词检索(问题)[0]
    向结果 = 向量检索(问题)[0]
    词对 = "✅" if 词结果 == 原始文档[正确索引] else "❌"
    向对 = "✅" if 向结果 == 原始文档[正确索引] else "❌"
    print(f"\n问题：{问题}")
    print(f"  关键词法 → {词结果[:22]}…  {词对}")
    print(f"  向量法   → {向结果[:22]}…  {向对}")
    print(f"  正确答案 → {正确名}")
print("\n" + "=" * 64)
print("结论：口语化/换说法的问题，关键词法靠字面翻车，向量法靠语义命中")
print("=" * 64)
