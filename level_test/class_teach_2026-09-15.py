# 基础版：class 最小四件套（结合你学过的 list / for / append）
# 类比：class = 笔记本的"设计图"，__init__ = 出厂时写好的设置，self = "这个笔记本"

class 笔记本:
    def __init__(self, 主人):        # 死记：__init__ 是"出厂设置"，self 必须排第一
        self.主人 = 主人             # 懂框架：self.主人 = 把值绑到"这个笔记本"上
        self.条目 = []               # 懂框架：每个笔记本自带一个空清单（list 你学过）

    def 写(self, 内容):              # 死记：方法第一个参数永远是 self
        self.条目.append(内容)       # 懂框架：往自己的清单追加一条（append 你学过）

    def 念(self):                    # 死记：又是一个方法
        print(f"{self.主人}的笔记本：")
        for 条 in self.条目:         # 懂框架：for 遍历你学过的
            print(" -", 条)

# 实例化（造出真实笔记本）懂框架：类名() = 造对象，这里只传 主人
小明的本 = 笔记本("小明")            # 死记：调用时不用写 self，只传 主人
小红的本 = 笔记本("小红")

小明的本.写("今天学了 class")
小明的本.写("self 是'这个本'")
小红的本.写("Python 看缩进")

小明的本.念()
小红的本.念()
print("小明的本.主人 =", 小明的本.主人)   # 访问属性：小明
