# 称号表：名字 -> 称号
称号表 = {
    "楚尘": "诸天塔主",
    "耿忻": "磨墨人",
    "李白": "诗仙",
}

print("输入名字查称号，输入 退出 结束")
while True:                      # ① while True = 一直循环，靠 break 跳出
    名字 = input("你叫什么？ ")
    if 名字 == "退出":           # ② 满足条件就跳出循环，否则死循环
        print("拜拜")
        break
    称号 = 称号表.get(名字)      # ③ .get 取值，键没有就返回 None（不崩）
    if 称号 is None:
        print(f"没查到 {名字} 的称号")
    else:
        print(f"{名字} 的称号是：{称号}")
