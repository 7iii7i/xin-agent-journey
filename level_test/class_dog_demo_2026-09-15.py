# class 换例子：用「狗」讲 self（每条狗独立）
class 狗:
    def __init__(self, 名字, 品种):
        self.名字 = 名字          # 给这条狗贴「名字」标签
        self.品种 = 品种          # 给这条狗贴「品种」标签
        self.饱腹 = 0             # 饱腹度，0 = 还饿着

    def 叫(self):
        print(f"{self.名字}（{self.品种}）：汪汪！")

    def 吃饭(self, 几口):
        self.饱腹 = self.饱腹 + 几口   # 只长「这一条狗」的饱腹度
        print(f"{self.名字} 吃了 {几口} 口，现在饱腹度 {self.饱腹}")

# 照图纸造两条真狗（每写一次 狗() 造一只）
旺财 = 狗("旺财", "土狗")
小白 = 狗("小白", "萨摩耶")

旺财.吃饭(3)     # 旺财吃 3 口
小白.吃饭(1)     # 小白只吃 1 口
旺财.叫()
小白.叫()

print("旺财的饱腹：", 旺财.饱腹)   # 3
print("小白的饱腹：", 小白.饱腹)   # 1（互不干扰）
