class 笔记本:
    def __init__(self, 主人):              # __init__ 本身就是个函数(方法)，下面缩进=函数体
        print("  [__init__ 这个函数被自动运行了]")
        self.主人 = 主人
        self.条目 = []

    def 写(self, 内容):                    # 另一个方法(也是函数)，首参 self
        self.条目.append(内容)

    def 念(self):                          # 又一个方法
        print(f"{self.主人}的笔记本：", self.条目)

# 造对象 → Python 自动调 __init__（正如你说的"造狗本来就要运行他"）
小明的本 = 笔记本("小明")
# 调普通方法（和调函数一样，点号自动把"这个本"塞进 self）
小明的本.写("今天搞懂了 __init__ 就是个函数")
小明的本.念()
