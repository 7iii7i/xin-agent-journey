# 完全不用 class，只用你已经会的：字典 + 函数 + 列表
def 造笔记本(主人):
    本 = {"主人": 主人, "条目": []}   # 字典，你学过
    return 本

def 写(本, 内容):                      # 函数，第一个参数就是"这个本"
    本["条目"].append(内容)            # 往字典里的列表追加，你学过

def 念(本):
    print(本["主人"], "的笔记本：")
    for 条 in 本["条目"]:
        print(" -", 条)

小明的本 = 造笔记本("小明")           # 造出一本
写(小明的本, "今天学了 class")         # 调用时把"本"自己传进去
写(小明的本, "self 就是那个'本'")
念(小明的本)
print("小明的本['主人'] =", 小明的本["主人"])
