# 函数底层全景：从"打包代码"到"参数传递"到"return"

# ===== 1. 函数是什么：一段打包好的、喊名字就跑的代码 =====
def 打招呼(名字):                       # 定义时：名字 = 空盒子(形参)
    print("你好呀，" + 名字)

print("=== 1. 定义好了，喊名字就跑 ===")
打招呼("小明")                          # 调用时："小明" 塞进 名字 这个盒子
打招呼("小红")


# ===== 2. 形参(定义时的空盒子) vs 实参(调用时的真值) =====
# def 打招呼(名字):   名字 是【形参】——定义时空空如也，只占个位
# 打招呼("小明")      "小明" 是【实参】——调用时按位置填进形参


# ===== 3. return：函数干完活"交出来的结果" =====
def 加(a, b):                           # a、b 是形参
    return a + b                        # return = 把算出的结果交出来

结果 = 加(3, 5)                         # 3、5 是实参，分别填进 a、b
print("=== 3. return 交出的结果 ===", 结果)


# ===== 4. 没有 return，函数就交不出东西（拿到 None）=====
def 只打印(a):
    print("只打印不返回:", a)            # 没写 return

空 = 只打印(10)
print("=== 4. 没 return，接到的 ===", 空)   # 打印 None


# ===== 5. 调用时 Python 按位置偷偷填：第1个→a，第2个→b =====
def 自我介绍(姓名, 年龄):
    print(f"我是{姓名}，{年龄}岁")

print("=== 5. 按位置填：第1个→姓名，第2个→年龄 ===")
自我介绍("阿强", 25)
