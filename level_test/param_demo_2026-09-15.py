# 演示：函数里的"本" "内容"到底是什么

def 写(本, 内容):                 # ① 定义时：本、内容 只是两个空名字，里面啥都没有
    print(f"  >>> 进函数了，此刻：本={本}，内容={内容}")
    本["条目"].append(内容)        # 把"内容"放进"本"这个笔记本的清单里

小明的本 = {"主人": "小明", "条目": []}   # 一个真笔记本（字典）

print("调用前 小明的本 =", 小明的本)
写(小明的本, "今天学了 class")      # ② 调用时：把"小明的本"塞给 本，把"今天学了 class"塞给 内容
print("调用后 小明的本 =", 小明的本)
