# 第一步：先不写任何方法，只看"照图纸造一个东西"长啥样
class 狗:
    pass   # pass = 暂时啥也不做，留空

旺财 = 狗()                      # 照"狗"这份图纸，造出一只真狗，取名 旺财
print("旺财是：", 旺财)
print("旺财的类型：", type(旺财))

# 第二步：给这只狗贴两个标签（标签 = 属性）
旺财.名字 = "旺财"
旺财.品种 = "土狗"
print("旺财的名字：", 旺财.名字)
print("旺财的品种：", 旺财.品种)

# 第三步：再照同一份图纸造一只，两只互不影响
小白 = 狗()
小白.名字 = "小白"
小白.品种 = "萨摩耶"
print("---- 两只狗各自独立 ----")
print("旺财：", 旺财.名字, 旺财.品种)
print("小白：", 小白.名字, 小白.品种)
