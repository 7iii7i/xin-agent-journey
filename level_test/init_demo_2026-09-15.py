# ===== 函数版：造笔记本（你已经懂的"出厂设置"）=====
def 造笔记本(主人):
    print(f"[函数版] 出厂设置：把主人设为 {主人}")
    本 = {"主人": 主人, "条目": []}
    return 本

小明的本 = 造笔记本("小明")
print("  造好了：", 小明的本, "\n")


# ===== class 版：__init__ 就是上面的"出厂设置"那段代码 =====
class 笔记本:
    def __init__(self, 主人):                 # 🔴 死记骨架：def __init__(self, 参数):
        print(f"[_init_] 自动跑了：把主人设为 {主人}")
        self.主人 = 主人                       # 把数据绑到"这个对象"上
        self.条目 = []                         # 每个新本自带空清单

print("下面只写 笔记本(\"小明\")，没手动调 __init__，看它跑不跑：")
小明的本2 = 笔记本("小明")                     # 造对象那一刻，__init__ 自动执行
print("  造好了：主人 =", 小明的本2.主人, "| 条目 =", 小明的本2.条目)
