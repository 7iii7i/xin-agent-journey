# class 学生: —— 画图纸
# __init__(self, 姓名, 年龄)：把 姓名、年龄 存到 self（self.姓名 / self.年龄）
# 方法 介绍(self)：打印 我叫XXX，今年YY岁（XXX=姓名，YY=年龄）
# 方法 长大(self)：让这个学生的年龄 +1（self.年龄 = self.年龄 + 1），再打印 XXX 长大了一岁，现在YY岁
# 造两个学生：甲 = 学生("张三", 18)、乙 = 学生("李四", 20)
# 依次调用：甲.介绍() → 乙.介绍() → 甲.长大() → 甲.介绍()
# 期望输出（跑通后应该正好是这样）​：
#
# plaintext
#
# 我叫张三，今年18岁
# 我叫李四，今年20岁
# 张三 长大了一岁，现在 19 岁
# 我叫张三，今年19岁
class 学生:
    def __init__(self,姓名,年龄):
        self.姓名=姓名
        self.年龄=年龄
    def 介绍(self):
        print(f"我叫{self.姓名}，今年{self.年龄}岁")
    def 长大(self):
        self.年龄 = self.年龄 + 1
        print(f"{self.姓名},长大了一岁，现在{self.年龄}岁")
甲 = 学生("张三", 18)
乙 = 学生("李四", 20)
甲.介绍()
乙.介绍()
甲.长大()
甲.介绍()

