class 狗:
    pass

print("① 只写了 class 狗: —— 这只是画了张图纸，一只狗都还没造出来")
print("   此刻没有旺财、没有小白，什么狗都没有\n")

# ⬇⬇⬇ 下面这一句，才是"造出狗"的那一步 ⬇⬇⬇
旺财 = 狗()
# ⬆⬆⬆ 上面这一句，才是"造出狗"的那一步 ⬆⬆⬆

print("② 执行了 旺财 = 狗() 之后，旺财才是一只真实存在的狗：")
print("   ", 旺财)
print("   它的类型是：", type(旺财), "\n")

# 再写一次 狗()，又造一只全新的
小白 = 狗()
print("③ 再写 小白 = 狗()，又照图纸造了一只全新的狗：", 小白)
print("   旺财 和 小白 是两只不同的狗：", 旺财 is not 小白)
